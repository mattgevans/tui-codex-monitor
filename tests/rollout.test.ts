import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, appendFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { DesktopObserver } from '../src/observer';
import { RolloutReader } from '../src/upstream/codex/rollout';

test('CLI rollout fallback follows complete records, completion, resume, stale work and replacement', () => {
  const home = mkdtempSync('/tmp/tcm-rollout-');
  const path = join(home, 'session.jsonl');
  const id = 'test-cli-thread';
  const now = Date.now();
  const record = (type: string, turn = 'turn-1', at = now) => JSON.stringify({ type: 'event_msg', timestamp: new Date(at).toISOString(), payload: { type, turn_id: turn, last_agent_message: 'private response' } }) + '\n';
  const meta = JSON.stringify({ type: 'session_meta', payload: { id, originator: 'codex-tui' } }) + '\n';
  const db = new DatabaseSync(join(home, 'state_5.sqlite'));
  db.exec('CREATE TABLE threads(id TEXT,title TEXT,cwd TEXT,source TEXT,archived INTEGER,updated_at INTEGER,rollout_path TEXT)');
  db.prepare('INSERT INTO threads VALUES(?,?,?,?,0,?,?)').run(id, 'CLI task', '/tmp/project', 'vscode', now / 1000, path);
  let openPaths: Set<string> | undefined;
  const observer = new DesktopObserver(home, () => openPaths);
  try {
    writeFileSync(path, meta + record('task_started'));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'WORKING');
    assert.equal(observer.agents[0].evidence, 'history');
    assert.equal(JSON.stringify(observer.agents).includes('private response'), false);
    const completion = record('task_complete');
    appendFileSync(path, completion.slice(0, -1));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'WORKING', 'partial record is ignored');
    appendFileSync(path, '\n');
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'DONE');
    assert.equal(observer.agents[0].status, 'review');
    assert.ok(observer.agents[0].attentionToken);
    appendFileSync(path, record('task_started', 'turn-2') + record('task_complete', 'turn-1'));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'WORKING', 'late older completion does not end new turn');
    appendFileSync(path, record('turn_aborted', 'turn-2'));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'DONE');
    writeFileSync(path, meta + record('task_started', 'turn-3', now - 180_000));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'UNKNOWN', 'killed/stale CLI must not remain working');
    appendFileSync(path, record('token_count', 'turn-3'));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'WORKING');
    openPaths = new Set();
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'EXITED');
    assert.equal(observer.agents[0].attentionToken, null);
    writeFileSync(path, meta + record('task_started', 'turn-4', now - 180_000));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'EXITED', 'abrupt exit detected even with stale log');
    openPaths.add(path);
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'WORKING', 'open process survives long quiet work');
    appendFileSync(path, record('task_complete', 'turn-4'));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'DONE', 'finished turn is distinct from exited process');
    openPaths.clear();
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'EXITED');
    writeFileSync(path, meta.replace(id, 'different-session') + record('task_complete'));
    observer.refresh();
    assert.equal(observer.agents[0].runtime, 'UNKNOWN', 'verify exact session identity');
    assert.equal(new RolloutReader().read('/missing', id), undefined);
  } finally {
    observer.stop(); db.close(); rmSync(home, { recursive: true, force: true });
  }
});
